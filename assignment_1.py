import pandas as pd
import numpy as np

df = pd.read_csv('/content/drive/MyDrive/Dataset/Assignment 1/car.csv')
df.head()

# NULL Values
df.isnull().sum()

# Null Values only in AnnualSalary
df['AnnualSalary'].isnull().sum()

#Dropping rows which have atleast one null value in any field
df.dropna(how='any', inplace=True)
print(df.shape)

# Task 5-Dropping the rows which have null values in all the fields
df.dropna(how='all', inplace=True)
print(df.shape)

# Task 6- Dropping the columns where there are null value in any record
df.dropna(axis=1, how='any', inplace=True)
print(df.columns)

# Task 7 - Dropping columns where there are null values in all records
df.dropna(axis=1, how='all', inplace=True)
print(df.columns)

#Task 8- Creating copy of dataset and replacing the null values in AnnualSalary with 70000
df_copy = df.copy()
df_copy['AnnualSalary'] = df_copy['AnnualSalary'].fillna(70000)
print(df_copy.columns)
print(df_copy.shape)

#Task 9- Replace the null values in Age with 0
df['Age'] = df['Age'].fillna(0)
print(df.columns)
print(df.shape)

#Task 10- Replace the null values in AnnualSalary with mean of the values
df['AnnualSalary'] = df['AnnualSalary'].fillna(df['AnnualSalary'].mean())
print(df.columns)
print(df.shape)

#Task 11- Replace the null values in Age with median of the values
df['Age'] = df['Age'].fillna(df['Age'].median())
print(df.columns)
print(df.shape)

#Task 12- Replace the null values in Gender with suitable measure of central tendency
df['Gender'] = df['Gender'].fillna(df['Gender'].mode()[0])
print(df.columns)
print(df.shape)

#Task 13- Check for duplicates
print(df.duplicated().sum())

#Task 14 - Remove the duplicate record
df.drop_duplicates(inplace=True)
